import { useState } from 'react';
import type { Alert } from '../api/dashboard';

type AlertStatus =
  | 'open'
  | 'investigating'
  | 'resolved';

interface AlertsPageProps {
  alerts: Alert[];
  onAlertStatusChange: (
    alertId: string,
    status: AlertStatus,
  ) => Promise<Alert>;
}

export default function AlertsPage({
  alerts,
  onAlertStatusChange,
}: AlertsPageProps) {
  const [expandedAlert, setExpandedAlert] =
    useState<string | null>(null);

  const [updatingAlert, setUpdatingAlert] =
    useState<string | null>(null);

  const [error, setError] = useState<string | null>(
    null,
  );

  /* =====================================================
     ALERT COUNTS
     ===================================================== */

  const highCriticalCount = alerts.filter(
    (alert) =>
      ['high', 'critical'].includes(
        alert.severity.toLowerCase(),
      ),
  ).length;

  const openCount = alerts.filter(
    (alert) =>
      alert.status.toLowerCase() === 'open',
  ).length;

  const investigatingCount = alerts.filter(
    (alert) =>
      alert.status.toLowerCase() ===
      'investigating',
  ).length;

  const resolvedCount = alerts.filter(
    (alert) =>
      alert.status.toLowerCase() ===
      'resolved',
  ).length;

  /* =====================================================
     STATUS UPDATE
     ===================================================== */

  const handleStatusChange = async (
    alertId: string,
    status: AlertStatus,
  ) => {
    setUpdatingAlert(alertId);
    setError(null);

    try {
      await onAlertStatusChange(
        alertId,
        status,
      );
    } catch (err) {
      setError(
        err instanceof Error
          ? err.message
          : 'Unable to update alert status.',
      );
    } finally {
      setUpdatingAlert(null);
    }
  };

  /* =====================================================
     FORMATTERS
     ===================================================== */

  const formatDateTime = (
    value: string,
  ) => {
    const date = new Date(value);

    if (Number.isNaN(date.getTime())) {
      return 'Not available';
    }

    return date.toLocaleString([], {
      day: '2-digit',
      month: 'short',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    });
  };

  const formatStatus = (
    status: string,
  ) => {
    return (
      status.charAt(0).toUpperCase() +
      status.slice(1).toLowerCase()
    );
  };

  const formatSeverity = (
    severity: string,
  ) => {
    return (
      severity.charAt(0).toUpperCase() +
      severity.slice(1).toLowerCase()
    );
  };

  /* =====================================================
     PAGE
     ===================================================== */

  return (
    <section className="page-content">

      {/* =================================================
          PAGE HEADER
          ================================================= */}

      <div className="page-header">
        <div>
          <div className="eyebrow">
            SOC OPERATIONS <span>•</span> DETECTION
          </div>

          <h1>Security Alerts</h1>

          <p>
            Review, investigate, and resolve alerts
            generated by AEGIS detection rules.
          </p>
        </div>

        <div className="operational-badge">
          <div className="status-dot" />

          <div>
            <span>ALERT ENGINE</span>
            <strong>Operational</strong>
          </div>
        </div>
      </div>

      {/* =================================================
          ALERT METRICS
          ================================================= */}

      <div className="metric-grid page-metrics">

        <div className="metric-card">
          <div className="metric-top">
            <span>Total Alerts</span>
          </div>

          <div className="metric-value">
            {alerts.length}
          </div>

          <div className="metric-change">
            Live from AEGIS API
          </div>
        </div>

        <div className="metric-card warning">
          <div className="metric-top">
            <span>High / Critical</span>
          </div>

          <div className="metric-value">
            {highCriticalCount}
          </div>

          <div className="metric-change">
            Requires attention
          </div>
        </div>

        <div className="metric-card cyan">
          <div className="metric-top">
            <span>Investigating</span>
          </div>

          <div className="metric-value">
            {investigatingCount}
          </div>

          <div className="metric-change">
            Analyst activity
          </div>
        </div>

        <div className="metric-card">
          <div className="metric-top">
            <span>Resolved</span>
          </div>

          <div className="metric-value">
            {resolvedCount}
          </div>

          <div className="metric-change">
            Closed alert workflow
          </div>
        </div>

      </div>

      {/* =================================================
          API ERROR
          ================================================= */}

      {error && (
        <div className="alert-error">
          <strong>Alert update failed:</strong>{' '}
          {error}
        </div>
      )}

      {/* =================================================
          ALERT REGISTER
          ================================================= */}

      <div className="table-card page-table">

        {/* REGISTER HEADER */}

        <div className="table-header">

          <div>
            <h3>Alert Register</h3>

            <span>
              Detection events currently recorded by
              AEGIS
            </span>
          </div>

          <div className="alert-register-summary">
            <span>
              {openCount} open
            </span>

            <span>•</span>

            <span>
              {investigatingCount} investigating
            </span>
          </div>

        </div>

        {/* ALERT LIST */}

        <div className="page-table-scroll">

          {alerts.length === 0 ? (
            <div className="empty-state">
              No alerts available.
            </div>
          ) : (
            alerts.map((alert) => {

              const status =
                alert.status.toLowerCase();

              const severity =
                alert.severity.toLowerCase();

              const isExpanded =
                expandedAlert === alert.id;

              const isUpdating =
                updatingAlert === alert.id;

              return (
                <div
                  className={`alert-record ${
                    isExpanded
                      ? 'alert-record-expanded'
                      : ''
                  }`}
                  key={alert.id}
                >

                  {/* =====================================
                      ALERT SUMMARY
                      ===================================== */}

                  <div className="alert-summary">

                    {/* ALERT TITLE */}

                    <div className="page-record-main">
                      <strong>
                        {alert.title}
                      </strong>

                      <span>
                        {alert.rule_id} •{' '}
                        {alert.source_ip ??
                          'No source IP'}
                      </span>
                    </div>

                    {/* SEVERITY */}

                    <span
                      className={`table-badge ${severity}`}
                    >
                      {formatSeverity(
                        alert.severity,
                      )}
                    </span>

                    {/* STATUS */}

                    <span
                      className={`table-badge ${status}`}
                    >
                      {formatStatus(
                        alert.status,
                      )}
                    </span>

                    {/* EVENT COUNT */}

                    <span className="page-record-meta">
                      {alert.event_count} events
                    </span>

                    {/* INVESTIGATE */}

                    <button
                      type="button"
                      className="alert-expand-button"
                      aria-expanded={isExpanded}
                      aria-label={
                        isExpanded
                          ? `Hide investigation details for ${alert.title}`
                          : `Investigate ${alert.title}`
                      }
                      onClick={() =>
                        setExpandedAlert(
                          isExpanded
                            ? null
                            : alert.id,
                        )
                      }
                    >
                      {isExpanded
                        ? 'Hide'
                        : 'Investigate'}
                    </button>

                  </div>

                  {/* =====================================
                      INVESTIGATION DETAILS
                      ===================================== */}

                  {isExpanded && (
                    <div className="alert-details">

                      {/* DETAIL GRID */}

                      <div className="alert-detail-grid">

                        <DetailItem
                          label="Rule ID"
                          value={alert.rule_id}
                        />

                        <DetailItem
                          label="Source IP"
                          value={
                            alert.source_ip ??
                            'Not available'
                          }
                        />

                        <DetailItem
                          label="Username"
                          value={
                            alert.username ??
                            'Not available'
                          }
                        />

                        <DetailItem
                          label="Asset ID"
                          value={
                            alert.asset_id ??
                            'Not linked'
                          }
                        />

                        <DetailItem
                          label="Event Count"
                          value={String(
                            alert.event_count,
                          )}
                        />

                        <DetailItem
                          label="Created"
                          value={formatDateTime(
                            alert.created_at,
                          )}
                        />

                      </div>

                      {/* =================================
                          DETECTION DESCRIPTION
                          ================================= */}

                      <div className="alert-description">

                        <div className="alert-detail-label">
                          Detection Description
                        </div>

                        <p>
                          {alert.description ||
                            'No description available.'}
                        </p>

                      </div>

                      {/* =================================
                          ANALYST ACTIONS
                          ================================= */}

                      <div className="alert-actions">

                        <span className="alert-action-label">
                          Analyst Action
                        </span>

                        {status === 'open' && (
                          <ActionButton
                            label="Start Investigation"
                            disabled={isUpdating}
                            onClick={() =>
                              handleStatusChange(
                                alert.id,
                                'investigating',
                              )
                            }
                          />
                        )}

                        {status ===
                          'investigating' && (
                          <ActionButton
                            label="Resolve Alert"
                            disabled={isUpdating}
                            onClick={() =>
                              handleStatusChange(
                                alert.id,
                                'resolved',
                              )
                            }
                          />
                        )}

                        {status === 'resolved' && (
                          <ActionButton
                            label="Reopen Investigation"
                            disabled={isUpdating}
                            onClick={() =>
                              handleStatusChange(
                                alert.id,
                                'investigating',
                              )
                            }
                          />
                        )}

                        {isUpdating && (
                          <span className="alert-updating">
                            Updating alert…
                          </span>
                        )}

                      </div>

                    </div>
                  )}

                </div>
              );
            })
          )}

        </div>
      </div>

    </section>
  );
}


/* =========================================================
   DETAIL ITEM
   ========================================================= */

function DetailItem({
  label,
  value,
}: {
  label: string;
  value: string;
}) {
  return (
    <div className="alert-detail-item">

      <span className="alert-detail-label">
        {label}
      </span>

      <span className="alert-detail-value">
        {value}
      </span>

    </div>
  );
}


/* =========================================================
   ACTION BUTTON
   ========================================================= */

function ActionButton({
  label,
  disabled,
  onClick,
}: {
  label: string;
  disabled: boolean;
  onClick: () => void;
}) {
  const variant =
    label === 'Start Investigation'
      ? 'investigate'
      : label === 'Resolve Alert'
        ? 'resolve'
        : 'reopen';

  return (
    <button
      type="button"
      disabled={disabled}
      onClick={onClick}
      className={`alert-action-button ${variant}`}
    >
      {label}
    </button>
  );
}